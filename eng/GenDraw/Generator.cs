                buf.Append(indent).Append($"int {lhs}i = {PixOffset("src", x, y, "*4", "*src.Stride")};\n");
                buf.Append(indent).Append($"uint {lhs}a{tmp} = (uint)src.Pix.Span[{lhs}i + 3] * 0x101;\n");
                buf.Append(indent).Append($"uint {lhs}r{tmp} = (uint)src.Pix.Span[{lhs}i + 0] * {lhs}a{tmp} / 0xff;\n");
                buf.Append(indent).Append($"uint {lhs}g{tmp} = (uint)src.Pix.Span[{lhs}i + 1] * {lhs}a{tmp} / 0xff;\n");
                buf.Append(indent).Append($"uint {lhs}b{tmp} = (uint)src.Pix.Span[{lhs}i + 2] * {lhs}a{tmp} / 0xff;");
                break;
            case "Rgba":
                buf.Append(indent).Append($"int {lhs}i = {PixOffset("src", x, y, "*4", "*src.Stride")};\n");
                buf.Append(indent).Append($"uint {lhs}r{tmp} = (uint)src.Pix.Span[{lhs}i + 0] * 0x101;\n");
                buf.Append(indent).Append($"uint {lhs}g{tmp} = (uint)src.Pix.Span[{lhs}i + 1] * 0x101;\n");
                buf.Append(indent).Append($"uint {lhs}b{tmp} = (uint)src.Pix.Span[{lhs}i + 2] * 0x101;\n");
                buf.Append(indent).Append($"uint {lhs}a{tmp} = (uint)src.Pix.Span[{lhs}i + 3] * 0x101;");
                break;
            case "YCbCr":
                buf.Append(indent).Append($"int {lhs}i = {PixOffset("src", x, y, "", "*src.YStride")};\n");
                buf.Append(indent).Append($"int {lhs}j = {COffset(x, y, d.Sratio)};\n");
                buf.Append(YcbcrToRgb(lhs, tmp, indent));
                break;
        }

        if (dollar == "srcf")
        {
            string[] chans;
            switch (d.SType)
            {
                default:
                    chans = new[] { "r", "g", "b", "a" };
                    break;
                case "Gray":
                    chans = new[] { "r" };
                    break;
                case "YCbCr":
                    chans = new[] { "r", "g", "b" };
                    break;
            }
            foreach (var c in chans)
            {
                string srcExpr = d.SType == "Rgba64"
                    ? $"{lhs}{tmp}.{c.ToUpperInvariant()}"
                    : $"{lhs}{c}{tmp}";
                string decl = eqOp == "+=" ? "" : "double ";
                buf.Append('\n').Append(indent).Append($"{decl}{lhs}{c} {eqOp} (double){srcExpr}{extra};");
            }
        }

        return buf.ToString().TrimEnd('\n');
    }

    private static string YcbcrToRgb(string lhs, string tmp, string ind)
    {
        var sb = new StringBuilder();
        sb.Append('\n').Append(ind).Append("// This is an inline version of the YCbCr.Rgba() conversion.\n");
        sb.Append(ind).Append($"int {lhs}yy1 = src.Y.Span[{lhs}i] * 0x10101;\n");
        sb.Append(ind).Append($"int {lhs}cb1 = src.Cb.Span[{lhs}j] - 128;\n");
        sb.Append(ind).Append($"int {lhs}cr1 = src.Cr.Span[{lhs}j] - 128;\n");
        sb.Append(ind).Append($"int {lhs}r{tmp} = ({lhs}yy1 + 91881 * {lhs}cr1) >> 8;\n");
        sb.Append(ind).Append($"int {lhs}g{tmp} = ({lhs}yy1 - 22554 * {lhs}cb1 - 46802 * {lhs}cr1) >> 8;\n");
        sb.Append(ind).Append($"int {lhs}b{tmp} = ({lhs}yy1 + 116130 * {lhs}cb1) >> 8;\n");
        foreach (var c in new[] { "r", "g", "b" })
        {
            sb.Append(ind).Append($"if ({lhs}{c}{tmp} < 0) {{ {lhs}{c}{tmp} = 0; }} else if ({lhs}{c}{tmp} > 0xffff) {{ {lhs}{c}{tmp} = 0xffff; }}\n");
        }
        return sb.ToString().TrimEnd('\n');
    }

