using System.Text;

namespace DotImage.GenDraw;

// Ports golang.org/x/image/draw/gen.go. Given the dsTypes table below it
// generates type-specialized Scale/Transform implementations (the "fast
// paths") plus dispatch switches, into DotImage.Extended.Draw's
// ScaleLeaf.Generated.cs.
internal sealed record GenData(string DType, string SType, string Sratio, string Receiver, string Op);

public static partial class Generator
{
    // ---- Type tables (gen.go dsTypes / init) ----

    // DsTypes are the (dst, src) pairs for which scale leaves are generated.
    // The last element is the fallback pair ("Image", "image.Image").
    internal static readonly (string D, string S)[] DsTypes =
    {
        ("Rgba", "Gray"),
        ("Rgba", "Nrgba"),
        ("Rgba", "Rgba"),
        ("Rgba", "YCbCr"),
        ("Rgba", "Rgba64"),
        ("Rgba", "Image"),
        ("Rgba64", "Rgba64"),
        ("Image", "Image"),
    };

    internal static readonly string[] DTypes = { "Rgba", "Rgba64", "Image" };
    internal static readonly string[] STypes = { "Gray", "Nrgba", "Rgba", "YCbCr", "Rgba64", "Image" };
    internal static readonly string[] SubsampleRatios = { "444", "422", "420", "440" };
    internal static readonly string[] Ops = { "Over", "Src" };

    // alwaysOpaque are those image types that are always opaque. For these
    // types, Over is equivalent to the faster Src, in the absence of a source
    // mask.
    internal static readonly string[] AlwaysOpaque = { "Gray", "YCbCr" };

    internal static readonly Dictionary<string, string[]> StypesForDtype = new()
    {
        ["Rgba"] = STypes,
        ["Rgba64"] = new[] { "Rgba64" },
        ["Image"] = new[] { "Image" },
        ["anyDType"] = STypes,
    };

    internal static string DstType(GenData d) => d.DType switch
    {
        "Rgba" => "RgbaImage",
        "Rgba64" => "ITargetRgba64Image",
        "Image" => "IWritableImage",
        _ => throw new Exception($"bad dType {d.DType}"),
    };

    internal static string SrcType(GenData d) => d.SType switch
    {
        "Gray" => "GrayImage",
        "Nrgba" => "NrgbaImage",
        "Rgba" => "RgbaImage",
        "YCbCr" => "YCbCrImage",
        "Rgba64" => "IRgba64Image",
        "Image" => "IImage",
        _ => throw new Exception($"bad sType {d.SType}"),
    };

    internal static string RecvCbScale(string r) => r switch { "Nn" => "NnScale", "Abl" => "AblScale", _ => throw new Exception($"bad receiver {r}") };
    internal static string RecvCbTransform(string r) => r switch { "Nn" => "NnTransform", "Abl" => "AblTransform", _ => throw new Exception($"bad receiver {r}") };

    internal static bool IsAlwaysOpaque(string sType) => Array.IndexOf(AlwaysOpaque, sType) >= 0;

    private static string Sp(int n) => new string(' ', n);

    // pixOffset mirrors gen.go; xstride/ystride are pre-composed C# substrings.
    private static string PixOffset(string m, string x, string y, string xstride, string ystride) =>
        $"({y}-{m}.Rect.Min.Y){ystride} + ({x}-{m}.Rect.Min.X){xstride}";

    private static string COffset(string x, string y, string sratio) => sratio switch
    {
        "444" => $"( {y}    - src.Rect.Min.Y  )*src.CStride + ( {x}    - src.Rect.Min.X  )",
        "422" => $"( {y}    - src.Rect.Min.Y  )*src.CStride + (({x})/2 - src.Rect.Min.X/2)",
        "420" => $"(({y})/2 - src.Rect.Min.Y/2)*src.CStride + (({x})/2 - src.Rect.Min.X/2)",
        "440" => $"(({y})/2 - src.Rect.Min.Y/2)*src.CStride + ( {x}    - src.Rect.Min.X  )",
        _ => throw new Exception($"unsupported sratio {sratio}"),
    };

    // ---- Main entry ----

    public static string Generate()
    {
        var w = new StringBuilder();
        w.Append(
            "// generated by \"dotnet run --project eng/GenDraw\". DO NOT EDIT.\n" +
            "\n" +
            "using System;\n" +
            "using DotImage;\n" +
            "using DotImage.Color;\n" +
            "using DotImage.Draw;\n" +
            "using DotImage.Extended.Math.F64;\n" +
            "using DotMath = System.Math;\n" +
            "#nullable enable\n" +
            "\n" +
            "namespace DotImage.Extended.Draw\n" +
            "{\n" +
            Sp(4) + "internal interface ITargetRgba64Image : IRgba64Image, ISetRgba64Image\n" +
            Sp(4) + "{\n" +
            Sp(4) + "}\n" +
            "\n");

        var scaleImpl = GenScaleImpl();
        w.Append(scaleImpl);

        w.Append("\n");
        w.Append(Sp(4) + "internal sealed partial class KernelScaler\n" + Sp(4) + "{\n");
        w.Append(GenKernelScalerBody(Sp(8)));
        w.Append(Sp(4) + "}\n");
        w.Append("}\n");

        return w.ToString();
    }

    // ---- ScaleImpl partial class: NN + ABL + Kernel.Transform ----

    private static string GenScaleImpl()
    {
        var w = new StringBuilder();
        w.Append(Sp(4) + "internal static partial class ScaleImpl\n" + Sp(4) + "{\n");

        foreach (var receiver in new[] { "Nn", "Abl" })
        {
            var d = new GenData("", "", "", receiver, "");
            w.Append(GenLeaves(CodeRoot, d, true));
            w.Append("\n");
            foreach (var t in DsTypes)
            {
                foreach (var op in Ops)
                {
                    if (op == "Over" && IsAlwaysOpaque(t.S))
                    {
                        continue;
                    }
                    GenLeafPair(w, CodeScaleLeafSource(receiver), CodeTransformLeafSource(receiver), t.D, t.S, receiver, op);
                }
            }
            w.Append("\n");
        }

        // Kernel.Transform (static, on ScaleImpl).
        w.Append(GenLeaves(KernelTransformRoot, new GenData("", "", "", "", ""), false));
        w.Append("\n");
        foreach (var t in DsTypes)
        {
            foreach (var op in Ops)
            {
                if (op == "Over" && IsAlwaysOpaque(t.S))
                {
                    continue;
                }
                GenLeafPair(w, CodeKernelTransformLeafSource, null, t.D, t.S, "", op);
            }
        }

        w.Append(Sp(4) + "}\n");
        return w.ToString();
    }

    private static void GenLeafPair(StringBuilder w, string scaleSource, string? transformSource, string dType, string sType, string receiver, string op)
    {
        var d = new GenData(dType, sType, "", receiver, op);
        w.Append(GenLeaves(scaleSource, d, false));
        if (transformSource != null)
        {
            w.Append("\n");
            w.Append(GenLeaves(transformSource, d, false));
        }
        w.Append("\n");
    }

    private static string GenKernelScalerBody(string indent)
    {
        var w = new StringBuilder();
        w.Append(GenLeaves(KernelScaleRoot, new GenData("", "", "", "", ""), false));
        w.Append("\n");
        foreach (var sType in STypes)
        {
            w.Append(GenLeaves(KernelScaleXLeaf, new GenData("", sType, "", "", ""), false));
        }
        w.Append("\n");
        foreach (var dType in DTypes)
        {
            foreach (var op in Ops)
            {
                w.Append(GenLeaves(KernelScaleYLeaf, new GenData(dType, "", "", "", op), false));
            }
        }
        return w.ToString();
    }

    // ---- expn / expnLine (gen.go) ----

    private static string GenLeaves(string code, GenData d, bool blankTop)
    {
        var w = new StringBuilder();
        // Mirrors gen.go expn(): for YCbCr sources, expand once per subsample
        // ratio so that each leaf is specialized to one ratio.
        if (d.SType == "YCbCr" && d.Sratio == "")
        {
            bool first = true;
            foreach (var sratio in SubsampleRatios)
            {
                w.Append(GenLeaves(code, d with { Sratio = sratio }, blankTop && first));
                first = false;
            }
            return w.ToString();
        }
        if (blankTop)
        {
            w.Append('\n');
        }
        foreach (var line in SplitLines(code))
        {
            string e = ExpnLine(line, d);
            if (e == ";")
            {
                continue;
            }
            w.Append(e);
            w.Append('\n');
        }
        return w.ToString();
    }

    private static IEnumerable<string> SplitLines(string code) => code.Split('\n');

    private static string ExpnLine(string line, GenData d)
    {
        while (true)
        {
            int i = line.IndexOf('$');
            if (i < 0)
            {
                break;
            }
            string prefix = line[..i];
            string s = line[(i + 1)..];

            i = s.Length;
            for (int j = 0; j < s.Length; j++)
            {
                if (!char.IsLetter(s[j]))
                {
                    i = j;
                    break;
                }
            }
            string dollar = s[..i];
            string suffix = s[i..];
            string indent = prefix[..(prefix.Length - prefix.TrimStart().Length)];

            string e = ExpnDollar(prefix, dollar, suffix, d, indent);
            if (e == "")
            {
                throw new Exception($"couldn't expand \"{line}\"");
            }
            line = e;
        }
        return line;
    }

    private static (string lhs, string eqOp) SplitEq(string s)
    {
        s = s.Trim();
        var (lhs1, _) = Split(s, ":=");
        if (lhs1 != "")
        {
            return (lhs1, ":=");
        }
        var (lhs2, _) = Split(s, "+=");
        if (lhs2 != "")
        {
            return (lhs2, "+=");
        }
        return ("", "");
    }

    private static (string[]? args, string extra) SplitArgs(string s)
    {
        s = s.Trim();
        if (s == "" || s[0] != '[')
        {
            return (null, "");
        }
        s = s[1..];
        int i = s.IndexOf(']');
        if (i < 0)
        {
            return (null, "");
        }
        var args = s[..i].Split(',').Select(t => t.Trim()).ToArray();
        string extra = s[(i + 1)..];
        return (args, extra);
    }

    private static (string a, string b) Split(string s, string sep)
    {
        int i = s.IndexOf(sep);
        if (i >= 0)
        {
            return (s[..i].Trim(), s[(i + sep.Length)..].Trim());
        }
        return ("", "");
    }

    private static string RelName(string s)
    {
        int i = s.LastIndexOf('.');
        return i >= 0 ? s[(i + 1)..] : s;
    }

    private static string Argf(string[] args, string s)
    {
        if (args.Length > 9)
        {
            throw new Exception("too many args");
        }
        for (int i = 0; i < args.Length; i++)
        {
            s = s.Replace("$" + i, args[i]);
        }
        return s;
    }

    // ---- Core expansion (gen.go expnDollar) ----

    private static string ExpnDollar(string prefix, string dollar, string suffix, GenData d, string indent)
    {
        switch (dollar)
        {
            case "dType":
            case "dTypeRN":
            case "sratio":
            case "sType":
            case "sTypeRN":
            case "receiver":
            case "op":
            case "cbScale":
            case "cbTransform":
                return SimpleToken(prefix, dollar, suffix, d);

            case "switch":
                return ExpandSwitch("", "", true, suffix, d.Receiver, LeadingWsOf(prefix));
            case "switchD":
                return ExpandSwitch("", "", false, suffix, d.Receiver, LeadingWsOf(prefix));
            case "switchS":
                return ExpandSwitch("", "anyDType", false, suffix, d.Receiver, LeadingWsOf(prefix));

            case "preOuter":
                return PreOuter(d, indent);
            case "preInner":
                return PreInner(d, indent);
            case "preKernelOuter":
                return PreKernelOuter(d, indent);
            case "preKernelInner":
                return PreKernelInner(d, indent);
            case "blend":
                return Blend(d, suffix, indent);
            case "clampToAlpha":
                return ClampToAlpha(d, indent);
            case "convFtou":
                return ConvFtou(d, suffix, indent);

            case "outputu":
                return OutputU(d, suffix, indent);
            case "outputf":
                return OutputF(d, suffix, indent);
            case "srcu":
            case "srcf":
                return Src(d, dollar, prefix, suffix, indent);

            case "tweakD":
                return d.DType == "Rgba" ? indent + "d += dst.Stride;" : ";";
            case "tweakDx":
                if (d.DType == "Rgba")
                {
                    int idx = prefix.IndexOf("dx++");
                    if (idx >= 0)
                    {
                        return prefix[..idx] + "dx++, d += 4" + prefix[(idx + 4)..];
                    }
                }
                return prefix;
            case "tweakDy":
                // Not used by the C# templates (the C# scaleY loop uses an indexed
                // dy and recomputes d via tweakD), kept for parity.
                return prefix;
            case "tweakP":
                // Mirrors gen.go: for Gray/YCbCr sources the trailing alpha slot
                // of the tmp array is 1.0; the remaining Gray slots duplicate pr.
                // (The C# kernel scaleX template uses $tmpOut instead of an array
                // literal, so this is kept only for fidelity with gen.go.)
                return d.SType switch
                {
                    "Gray" => prefix.TrimStart().StartsWith("pa * ") ? "1," : "pr,",
                    "YCbCr" => prefix.TrimStart().StartsWith("pa * ") ? "1," : prefix,
                    _ => prefix,
                };
            case "tweakPr":
                return d.SType == "Gray" ? indent + "pr *= b.InvTotalWeightFFFF;" : ";";
            case "tweakVarP":
                return d.SType switch
                {
                    "Gray" => indent + "double pr = 0;",
                    "YCbCr" => indent + "double pr = 0, pg = 0, pb = 0;",
                    _ => indent + "double pr = 0, pg = 0, pb = 0, pa = 0;",
                };
            case "tmpOut":
                return TmpOut(d, indent);
        }
        return "";
    }

    private static string SimpleToken(string prefix, string dollar, string suffix, GenData d)
    {
        string v = dollar switch
        {
            "dType" => DstType(d),
            "dTypeRN" => RelName(d.DType),
            "sratio" => d.Sratio,
            "sType" => SrcType(d),
            "sTypeRN" => RelName(d.SType),
            "receiver" => d.Receiver,
            "op" => d.Op,
            "cbScale" => RecvCbScale(d.Receiver),
            "cbTransform" => RecvCbTransform(d.Receiver),
            _ => throw new Exception("bad token"),
        };
        return prefix + v + suffix;
    }

    private static string LeadingWsOf(string prefix)
    {
        int n = prefix.Length - prefix.TrimStart().Length;
        return prefix[..n];
    }

    // ---- expnSwitch (gen.go) ----

    // dstVar is the pattern variable bound by the enclosing "case <dstType> d:"
    // label (or null when dst is still the method parameter, i.e. the switch is
    // at the top level or inside the dst switch's "default:"). Go's type-switch
    // shadowing is lexical: a call emitted inside a "case" (including an inner
    // switch's "default:") still sees the case-bound dst, so the generated call
    // must pass the bound variable. Similarly, srcVar is the pattern variable
    // bound by the src switch's case label, and is null in its "default:".
    private static string ExpandSwitch(string op, string dType, bool expandBoth, string template, string receiver, string indent, string? dstVar = null)
    {
        var sb = new StringBuilder();
        if (op == "" && dType != "anyDType")
        {
            sb.Append(indent).Append("switch (op)\n");
            sb.Append(indent).Append("{\n");
            foreach (var opv in Ops)
            {
                sb.Append(indent).Append(Sp(4)).Append("case Op.").Append(opv).Append(":\n");
                sb.Append(ExpandSwitch(opv, dType, expandBoth, template, receiver, indent + Sp(8), dstVar));
                sb.Append(indent).Append(Sp(8)).Append("break;\n");
            }
            sb.Append(indent).Append("}\n");
            return sb.ToString();
        }

        bool isSrc = dType != "";
        string switchVar = isSrc ? "src" : "dst";

        sb.Append(indent).Append("switch (").Append(switchVar).Append(")\n");
        sb.Append(indent).Append("{\n");

        string fallback;
        string[] values;
        if (dType != "")
        {
            fallback = "Image";
            values = StypesForDtype[dType];
        }
        else
        {
            fallback = "Image";
            values = DTypes;
        }

        foreach (var v in values)
        {
            if (dType != "" && op == "Over" && IsAlwaysOpaque(v))
            {
                continue;
            }

            if (v == fallback)
            {
                sb.Append(indent).Append(Sp(4)).Append("default:\n");
            }
            else
            {
                string label = isSrc ? SrcType(new GenData("", v, "", "", "")) : DstType(new GenData(v, "", "", "", ""));
                sb.Append(indent).Append(Sp(4)).Append("case ").Append(label).Append(' ').Append(isSrc ? "s" : "d").Append(":\n");
            }

            if (isSrc)
            {
                if (v == "YCbCr")
                {
                    sb.Append(ExpandSwitchYCbCr(op, dType, template, receiver, indent + Sp(8), dstVar));
                }
                else
                {
                    sb.Append(SwitchCall(template, new GenData(dType, v, "", receiver, op), dstVar, v == fallback ? null : "s", indent + Sp(8)));
                }
            }
            else if (!expandBoth)
            {
                sb.Append(SwitchCall(template, new GenData(v, "", "", receiver, op), v == fallback ? null : "d", null, indent + Sp(8)));
            }
            else
            {
                sb.Append(ExpandSwitch(op, v, false, template, receiver, indent + Sp(8), v == fallback ? null : "d"));
            }
            sb.Append(indent).Append(Sp(8)).Append("break;\n");
        }

        sb.Append(indent).Append("}\n");
        return sb.ToString();
    }

    private static string ExpandSwitchYCbCr(string op, string dType, string template, string receiver, string indent, string? dstVar)
    {
        var sb = new StringBuilder();
        sb.Append(indent).Append("switch (s.SubsampleRatio)\n");
        sb.Append(indent).Append("{\n");
        sb.Append(indent).Append(Sp(4)).Append("default:\n");
        sb.Append(SwitchCall(template, new GenData(dType, "Image", "", receiver, op), dstVar, "s", indent + Sp(8)));
        sb.Append(indent).Append(Sp(8)).Append("break;\n");
        foreach (var sratio in SubsampleRatios)
        {
            sb.Append(indent).Append(Sp(4)).Append("case YCbCrSubsampleRatio.Ratio").Append(sratio).Append(":\n");
            sb.Append(SwitchCall(template, new GenData(dType, "YCbCr", sratio, receiver, op), dstVar, "s", indent + Sp(8)));
            sb.Append(indent).Append(Sp(8)).Append("break;\n");
        }
        sb.Append(indent).Append("}\n");
        return sb.ToString();
    }

    private static string SwitchCall(string template, GenData d, string? dstVar, string? srcVar, string indent)
    {
        // The call line also carries the leaf-name tokens ($dTypeRN etc.) that
        // per-case data resolve. The literal parameters dst/src are rebound to
        // the pattern variables bound in the enclosing case labels, mirroring
        // Go's lexical type-switch shadowing. "default:" labels bind no pattern
        // variable, so dstVar/srcVar are null there and the original parameter
        // identifiers (dst/src) are kept.
        string call = ExpnLine(template.TrimStart(), d);
        if (dstVar != null)
        {
            call = call.Replace("dst", dstVar);
        }
        if (srcVar != null)
        {
            call = call.Replace("src", srcVar);
        }
        return indent + call + ";\n";
    }

    // ---- Snippet producers ----

    private static string PreOuter(GenData d, string ind)
    {
        string destMaskLine = ind + "IImage? dstMask = o.DstMask;\n" + ind + "Point dmp = o.DstMaskP;\n";
        switch (d.DType)
        {
            default:
                return ";";
            case "Image":
                string s = "";
                if (d.SType is "Image" or "Rgba64")
                {
                    s = ind + "IImage? srcMask = o.SrcMask;\n" + ind + "Point smp = o.SrcMaskP;\n";
                }
                return s + destMaskLine +
                    ind + "Rgba64 dstColorRGBA64 = new Rgba64(0, 0, 0, 0);";
            case "Rgba64":
                s = "";
                if (d.SType is "Image" or "Rgba64")
                {
                    s = ind + "IImage? srcMask = o.SrcMask;\n" + ind + "Point smp = o.SrcMaskP;\n";
                }
                return s + destMaskLine +
                    ind + "Rgba64 dstColorRGBA64 = new Rgba64(0, 0, 0, 0);";
        }
    }

    private static string PreInner(GenData d, string ind)
    {
        switch (d.DType)
        {
            default:
                return ";";
            case "Rgba":
                return ind + "int d = " + PixOffset("dst", "dr.Min.X+adr.Min.X", "dr.Min.Y+dy", "*4", "*dst.Stride") + ";";
        }
    }

    private static string PreKernelOuter(GenData d, string ind)
    {
        switch (d.SType)
        {
            default:
                return ";";
            case "Image":
            case "Rgba64":
                return ind + "IImage? srcMask = o.SrcMask;\n" + ind + "Point smp = o.SrcMaskP;";
        }
    }

    private static string PreKernelInner(GenData d, string ind)
    {
        switch (d.DType)
        {
            default:
                return ";";
            case "Rgba":
                return ind + "int d = " + PixOffset("dst", "dr.Min.X+dx", "dr.Min.Y+adr.Min.Y", "*4", "*dst.Stride") + ";";
        }
    }

    private static string Blend(GenData d, string suffix, string ind)
    {
        var (args, _) = SplitArgs(suffix);
        if (args == null || args.Length != 4)
        {
            return "";
        }
        var chans = d.SType switch
        {
            "Gray" => new[] { "r" },
            "YCbCr" => new[] { "r", "g", "b" },
            _ => new[] { "r", "g", "b", "a" },
        };
        var sb = new StringBuilder();
        foreach (var c in chans)
        {
            sb.Append(ind).Append($"{args[3]}{c} = {args[0]} * {args[1]}{c} + {args[2]} * {args[3]}{c};\n");
        }
        return sb.ToString().TrimEnd('\n');
    }

    private static string ClampToAlpha(GenData d, string ind)
    {
        if (IsAlwaysOpaque(d.SType))
        {
            return ";";
        }
        return ind + "if (pr > pa) { pr = pa; }\n" +
               ind + "if (pg > pa) { pg = pa; }\n" +
               ind + "if (pb > pa) { pb = pa; }";
    }

    private static string ConvFtou(GenData d, string suffix, string ind)
    {
        var (args, _) = SplitArgs(suffix);
        if (args == null || args.Length != 2)
        {
            return "";
        }
        string p = args[0], s = args[1];
        switch (d.SType)
        {
            default:
                return ind + $"uint {p}r = (uint){s}r;\n" +
                       ind + $"uint {p}g = (uint){s}g;\n" +
                       ind + $"uint {p}b = (uint){s}b;\n" +
                       ind + $"uint {p}a = (uint){s}a;";
            case "Gray":
                return ind + $"uint {p}r = (uint){s}r;";
            case "YCbCr":
                return ind + $"uint {p}r = (uint){s}r;\n" +
                       ind + $"uint {p}g = (uint){s}g;\n" +
                       ind + $"uint {p}b = (uint){s}b;";
            case "Rgba64":
                return ind + $"Rgba64 {p} = new Rgba64((ushort){s}r, (ushort){s}g, (ushort){s}b, (ushort){s}a);";
        }
    }

    // ---- srcu / srcf (gen.go) ----

    private static string Src(GenData d, string dollar, string prefix, string suffix, string indent)
    {
        var (lhs, eqOp) = SplitEq(prefix);
        if (lhs == "")
        {
            return "";
        }
        eqOp = eqOp.Replace(":=", "=");
        var (args, extra) = SplitArgs(suffix);
        if (args == null || args.Length != 2)
        {
            return "";
        }

        string tmp = dollar == "srcf" ? "u" : "";
        string x = args[0], y = args[1];
        var buf = new StringBuilder();

        switch (d.SType)
        {
            default:
                throw new Exception($"bad sType {d.SType}");
            case "Image":
            {
                string vars = indent + $"(uint {lhs}r{tmp}, uint {lhs}g{tmp}, uint {lhs}b{tmp}, uint {lhs}a{tmp}) = src.At({x}, {y}).Rgba();";
                buf.Append(vars);
